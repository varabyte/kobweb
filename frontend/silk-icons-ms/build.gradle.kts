val ICON_LIST_FILE_NAME = "ms-icon-list.txt"

@CacheableTask
abstract class FetchIconsTask : DefaultTask() {
    @get:Input
    abstract val sourceCommit: Property<String>

    @get:OutputFile
    abstract val iconsFile: RegularFileProperty

    // Material Symbols ships the same set of icons across all of its styles (outlined, rounded, sharp), so we only need
    // a single list of names. We still fetch every family, though, to verify that assumption holds.
    private val FAMILIES = listOf(
        "MaterialSymbolsOutlined",
        "MaterialSymbolsRounded",
        "MaterialSymbolsSharp",
    )

    // URL-encoded axis suffix: [FILL,GRAD,opsz,wght]
    private val MS_AXIS_SUFFIX = "%5BFILL%2CGRAD%2Copsz%2Cwght%5D"

    private fun fetchNames(sourceCommit: String, family: String): List<String> {
        val url = "https://raw.githubusercontent.com/google/material-design-icons/$sourceCommit/variablefont/$family$MS_AXIS_SUFFIX.codepoints"

        logger.lifecycle("Fetching $url")
        val connection = URI(url).toURL().openConnection()
        connection.setRequestProperty("User-Agent", "kobweb-silk-icons-ms-generator")
        val text = connection.getInputStream().use { it.readBytes().decodeToString() }

        val names = text.lineSequence()
            .filter { it.isNotBlank() }
            .map { it.substringBefore(' ') }
            .toList()

        if (names.isEmpty()) throw GradleException("No icon codepoints parsed for $family")
        return names
    }

    @TaskAction
    fun fetch() {
        val sourceCommit = sourceCommit.get()

        val namesByFamily = FAMILIES.associateWith { family -> fetchNames(sourceCommit, family) }
        val (primaryFamily, names) = namesByFamily.entries.first()
        namesByFamily.forEach { (family, familyNames) ->
            if (familyNames.toSet() != names.toSet()) {
                val missing = names - familyNames.toSet()
                val extra = familyNames - names.toSet()
                throw GradleException(
                    "Icon names for $family differ from $primaryFamily, but this task assumes they are the same. " +
                        "Missing: ${missing.take(10)}${if (missing.size > 10) " (+${missing.size - 10} more)" else ""}, " +
                        "extra: ${extra.take(10)}${if (extra.size > 10) " (+${extra.size - 10} more)" else ""}"
                )
            }
        }

        val iconsFile = iconsFile.get().asFile
        iconsFile.bufferedWriter().use { writer ->
            writer.appendLine("# See the README.md for more information about this file. It is parsed by this project's generateIcons gradle task.")
            writer.appendLine("# Generated by the fetchIcons task from google/material-design-icons @ $sourceCommit")
            names.forEach { writer.appendLine(it) }
        }
        logger.lifecycle("Wrote ${iconsFile.absolutePath}")
    }
}

val fetchMsIconsTask = tasks.register<FetchIconsTask>("fetchIcons") {
    group = "Icon"
    description = "Download information that lets us create $ICON_LIST_FILE_NAME, which is used to generate icons."

    sourceCommit.set("49d4db35df873165d6bd6ba09b063c7dafbac2f4")
    iconsFile.set(layout.projectDirectory.file(ICON_LIST_FILE_NAME))
