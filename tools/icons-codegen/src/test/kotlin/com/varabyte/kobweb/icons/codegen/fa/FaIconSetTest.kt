package com.varabyte.kobweb.icons.codegen.fa

import com.varabyte.kobweb.icons.codegen.IconCodegenOptions
import com.varabyte.kobweb.icons.codegen.IconVisibility
import com.varabyte.truthish.assertThat
import com.varabyte.truthish.assertThrows
import org.junit.Test
import java.io.File
import kotlin.io.path.createTempDirectory

class FaIconSetTest {
    private val rootDir = createTempDirectory("fa-icon-set-test").toFile().also { it.deleteOnExit() }
    private val iconsFile = rootDir.resolve("fa-icon-list.txt")
    private val outDir = rootDir.resolve("out")
    private val packageDir = outDir.resolve("test/icons")

    private fun generateBindings(iconsText: String, visibility: IconVisibility) {
        iconsFile.writeText(iconsText)
        FaIconSet().generateBindings(iconsFile, IconCodegenOptions(packageName = "test.icons", visibility), outDir)
    }

    private fun File.relativeFilePaths() = walkTopDown().filter { it.isFile }.map { it.relativeTo(this).path }.sorted().toList()

    @Test
    fun iconsFileListsFreeIconsPerCategory() {
        val iconsText = FaIconSet().iconsFileTextFor(
            "6.5.2",
            """
            {
              "address-book": {"label": "Address Book", "free": ["solid", "regular"]},
              "bell": {"label": "Bell", "free": ["solid"]},
              "github": {"label": "GitHub", "free": ["brands"]},
              "pro-only": {"label": "Pro Only", "free": []},
              "font-awesome": {"label": "Font Awesome", "free": ["brands", "solid", "regular"]}
            }
            """.trimIndent()
        )

        assertThat(iconsText).isEqualTo(
            """
            # THIS FILE IS AUTOGENERATED from FortAwesome/Font-Awesome @ 6.5.2. Fetch it again instead of editing it by hand.
            fas=address-book,bell,font-awesome
            far=address-book,font-awesome
            fab=github

            """.trimIndent()
        )
    }

    @Test
    fun generatesIconFilesPerCategory() {
        generateBindings(
            """
            # A comment
            fas=address-book,bell
            far=address-book
            fab=github
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_FaIcon.kt", "address-book.kt", "bell.kt", "github.kt")
        assertThat(packageDir.resolve("address-book.kt").readText()).isEqualTo(
            """
            // THIS FILE IS AUTOGENERATED from `fa-icon-list.txt`. Do not edit it by hand.
            //@formatter:off
            @file:Suppress("unused", "SpellCheckingInspection")

            package test.icons

            import androidx.compose.runtime.*
            import com.varabyte.kobweb.compose.ui.Modifier

            @Composable fun FaAddressBook(modifier: Modifier = Modifier, style: FaIconStyle = FaIconStyle.OUTLINE, size: FaIconSize? = null) = FaIcon("address-book", modifier, style.category, size)
            """.trimIndent()
        )
        assertThat(packageDir.resolve("bell.kt").readText()).endsWith(
            "\n@Composable fun FaBell(modifier: Modifier = Modifier, size: FaIconSize? = null) = FaIcon(\"bell\", modifier, FaIconCategory.SOLID, size)"
        )
        assertThat(packageDir.resolve("github.kt").readText()).endsWith(
            "\n@Composable fun FaGithub(modifier: Modifier = Modifier, size: FaIconSize? = null) = FaIcon(\"github\", modifier, FaIconCategory.BRAND, size)"
        )
    }

    @Test
    fun internalVisibilityAppliesToIconsAndSupportCode() {
        generateBindings(
            """
            fas=bell
            far=
            fab=
            """.trimIndent(),
            IconVisibility.INTERNAL,
        )

        assertThat(packageDir.resolve("bell.kt").readText()).contains("\n@Composable internal fun FaBell(")
        val supportCode = packageDir.resolve("_FaIcon.kt").readText()
        assertThat(supportCode).contains("\ninternal enum class FaIconCategory(")
        assertThat(supportCode).contains("\ninternal enum class FaIconStyle(")
        assertThat(supportCode).contains("\ninternal enum class FaIconSize(")
        assertThat(supportCode).contains("\ninternal fun FaIcon(")
    }

    @Test
    fun namesDifferingOnlyByDashesKeepTheLongestOne() {
        generateBindings(
            """
            fas=print-shop,printshop
            far=
            fab=
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_FaIcon.kt", "print-shop.kt")
    }

    @Test
    fun stylesheetIsLoadedForTheNewestVersion() {
        val stylesheet = FaIconSet().stylesheet
        assertThat(stylesheet.versionFor(listOf("6.5.2", "6.10.0", "6.7.1"))).isEqualTo("6.10.0")
    }

    @Test
    fun stylesheetServesOlderBindingsWithTheSameMajorVersion() {
        val stylesheet = FaIconSet().stylesheet
        assertThat(stylesheet.serves(stylesheetVersion = "6.7.1", bindingsVersion = "6.5.2")).isTrue()
        assertThat(stylesheet.serves(stylesheetVersion = "6.5.2", bindingsVersion = "6.5.2")).isTrue()
    }

    @Test
    fun stylesheetDoesNotServeNewerBindings() {
        val stylesheet = FaIconSet().stylesheet
        assertThat(stylesheet.serves(stylesheetVersion = "6.5.2", bindingsVersion = "6.7.1")).isFalse()
    }

    @Test
    fun stylesheetDoesNotServeBindingsWithAnotherMajorVersion() {
        val stylesheet = FaIconSet().stylesheet
        assertThat(stylesheet.serves(stylesheetVersion = "7.3.1", bindingsVersion = "6.5.2")).isFalse()
    }

    @Test
    fun brandsWithOtherStylesAreRejected() {
        val e = assertThrows<IllegalStateException> {
            generateBindings(
                """
                fas=font-awesome
                far=
                fab=font-awesome
                """.trimIndent(),
                IconVisibility.PUBLIC,
            )
        }
        assertThat(e.message!!).contains("Found unexpected groupings")
    }
}
