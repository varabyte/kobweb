@file:Suppress("SpellCheckingInspection")

package com.varabyte.kobweb.icons.codegen.material

import com.varabyte.kobweb.icons.codegen.IconCodegenOptions
import com.varabyte.kobweb.icons.codegen.IconVisibility
import com.varabyte.truthish.assertThat
import org.junit.Test
import java.io.File
import kotlin.io.path.createTempDirectory

class MdiIconSetTest {
    private val rootDir = createTempDirectory("mdi-icon-set-test").toFile().also { it.deleteOnExit() }
    private val iconsFile = rootDir.resolve("md-icon-list.txt")
    private val outDir = rootDir.resolve("out")
    private val packageDir = outDir.resolve("test/icons")

    private fun generateBindings(iconsText: String, visibility: IconVisibility) {
        iconsFile.writeText(iconsText)
        MdiIconSet().generateBindings(iconsFile, IconCodegenOptions(packageName = "test.icons", visibility), outDir)
    }

    private fun File.relativeFilePaths() = walkTopDown().filter { it.isFile }.map { it.relativeTo(this).path }.sorted().toList()

    @Test
    fun generatesIconFile() {
        generateBindings(
            """
            # A comment
            mdi=home
            mdio=home
            mdir=home
            mdis=home
            mdit=home
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_MdiIcon.kt", "home.kt")
        assertThat(packageDir.resolve("home.kt").readText()).isEqualTo(
            """
            // THIS FILE IS AUTOGENERATED from `md-icon-list.txt`. Do not edit it by hand.
            //@formatter:off
            @file:Suppress("unused", "SpellCheckingInspection")

            package test.icons

            import androidx.compose.runtime.*
            import com.varabyte.kobweb.compose.ui.Modifier
            import test.icons.IconStyle.*

            @Composable fun MdiHome(modifier: Modifier = Modifier, style: IconStyle = FILLED) = MdiIcon("home", modifier, style)
            """.trimIndent()
        )
    }

    @Test
    fun iconsInOneStyleTakeNoStyleParameter() {
        generateBindings(
            """
            mdi=
            mdio=
            mdir=
            mdis=
            mdit=tonality
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.resolve("tonality.kt").readText()).endsWith(
            "\n@Composable fun MdiTonality(modifier: Modifier = Modifier) = MdiIcon(\"tonality\", modifier, TWO_TONED)"
        )
    }

    @Test
    fun iconsInSomeStylesAssertTheStyleParameter() {
        generateBindings(
            """
            mdi=
            mdio=label
            mdir=label
            mdis=
            mdit=
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.resolve("label.kt").readText()).endsWith(
            "\n@Composable fun MdiLabel(modifier: Modifier = Modifier, style: IconStyle = OUTLINED) = MdiIcon(\"label\", modifier, style.also { it.assertValidStyle(\"MdiLabel\", OUTLINED, ROUNDED) })"
        )
    }

    @Test
    fun internalVisibilityAppliesToIconsAndSupportCode() {
        generateBindings(
            """
            mdi=home
            mdio=
            mdir=
            mdis=
            mdit=
            """.trimIndent(),
            IconVisibility.INTERNAL,
        )

        assertThat(packageDir.resolve("home.kt").readText()).contains("\n@Composable internal fun MdiHome(")
        val supportCode = packageDir.resolve("_MdiIcon.kt").readText()
        assertThat(supportCode).contains("\ninternal enum class IconStyle {")
        assertThat(supportCode).contains("\ninternal fun MdiIcon(")
    }

    @Test
    fun namesDifferingOnlyByUnderscoresKeepTheLongestOne() {
        generateBindings(
            """
            mdi=add_chart,addchart
            mdio=
            mdir=
            mdis=
            mdit=
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_MdiIcon.kt", "add_chart.kt")
    }
}
