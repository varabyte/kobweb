@file:Suppress("SpellCheckingInspection")

package com.varabyte.kobweb.icons.codegen

import com.varabyte.truthish.assertThat
import com.varabyte.truthish.assertThrows
import org.junit.Test
import java.io.File
import kotlin.io.path.createTempDirectory

class LucideIconSetTest {
    private val rootDir = createTempDirectory("lucide-icon-set-test").toFile().also { it.deleteOnExit() }
    private val dataFile = rootDir.resolve("lucide-icons.json")
    private val outDir = rootDir.resolve("out")
    private val packageDir = outDir.resolve("test/icons")

    private fun generateIconFile(dataJson: String, visibility: IconVisibility) {
        dataFile.writeText(dataJson)
        LucideIconSet().generate(dataFile, IconCodegenOptions(packageName = "test.icons", visibility), outDir)
    }

    private fun File.relativeFilePaths() = walkTopDown().filter { it.isFile }.map { it.relativeTo(this).path }.sorted().toList()

    @Test
    fun generatesIconFile() {
        generateIconFile(
            """
            {
              "version": "1.0.0",
              "icons": {
                "arrow-right": [{"tag":"path","attrs":{"d":"M5 12h14"}},{"tag":"circle","attrs":{"cx":"16","cy":"4","r":"1"}}]
              },
              "deprecated": {}
            }
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("arrow-right.kt")
        assertThat(packageDir.resolve("arrow-right.kt").readText()).isEqualTo(
            """
            //@formatter:off
            @file:Suppress("unused", "SpellCheckingInspection", "PackageDirectoryMismatch")

            // !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
            // THIS FILE IS AUTOGENERATED.
            //
            // Do not edit this file by hand. Instead, run the `fetchLucideIcons` Gradle task to update
            // `lucide-icons.json` in the module root, then run the Gradle task "generateIcons".
            // !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

            package test.icons

            import androidx.compose.runtime.Composable
            import com.varabyte.kobweb.compose.dom.svg.SVGStrokeLineCap
            import com.varabyte.kobweb.compose.dom.svg.SVGStrokeLineJoin
            import com.varabyte.kobweb.compose.dom.svg.ViewBox
            import com.varabyte.kobweb.compose.ui.Modifier
            import com.varabyte.kobweb.compose.ui.toAttrs
            import com.varabyte.kobweb.silk.components.icons.IconRenderStyle
            import com.varabyte.kobweb.silk.components.icons.createIcon
            import org.jetbrains.compose.web.css.*
            import com.varabyte.kobweb.compose.dom.svg.Circle
            import com.varabyte.kobweb.compose.dom.svg.Path

            @Composable
            fun LucideArrowRight(
                modifier: Modifier = Modifier, strokeWidth: Number = 2,
            ) {
                createIcon(
                    viewBox = ViewBox.sized(24),
                    renderStyle = IconRenderStyle.Stroke(strokeWidth),
                    attrs = modifier.toAttrs {
                        strokeLineCap(SVGStrokeLineCap.Round)
                        strokeLineJoin(SVGStrokeLineJoin.Round)
                    }
                ) {
                    Path {
                        d("M5 12h14")
                    }
                    Circle {
                        cx(16)
                        cy(4)
                        r(1)
                    }
                }
            }

            """.trimIndent()
        )
    }

    @Test
    fun internalVisibilityAppliesToIconsAndDeprecatedAliases() {
        generateIconFile(
            """
            {
              "version": "1.0.0",
              "icons": {
                "circle-x": [{"tag":"path","attrs":{"d":"m15 9-6 6"}}]
              },
              "deprecated": {"x-circle":"circle-x"}
            }
            """.trimIndent(),
            IconVisibility.INTERNAL,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("circle-x.kt", "deprecated/x-circle.kt")
        assertThat(packageDir.resolve("circle-x.kt").readText()).contains("\ninternal fun LucideCircleX(\n")
        assertThat(packageDir.resolve("deprecated/x-circle.kt").readText()).contains(
            """
            @Deprecated("Use LucideCircleX instead.", ReplaceWith("LucideCircleX(modifier = modifier, strokeWidth = strokeWidth)"))
            @Composable
            internal fun LucideXCircle(
                modifier: Modifier = Modifier, strokeWidth: Number = 2,
            ) = LucideCircleX(modifier = modifier, strokeWidth = strokeWidth)
            """.trimIndent()
        )
    }

    @Test
    fun namesDifferingOnlyByCaseGetSeparateFiles() {
        generateIconFile(
            """
            {
              "version": "1.0.0",
              "icons": {
                "letter-s": [{"tag":"path","attrs":{"d":"M1 1"}}],
                "letters": [{"tag":"path","attrs":{"d":"M2 2"}}]
              },
              "deprecated": {}
            }
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("letter-s.kt", "letters.kt")
        assertThat(packageDir.resolve("letter-s.kt").readText()).contains("\nfun LucideLetterS(\n")
        assertThat(packageDir.resolve("letters.kt").readText()).contains("\nfun LucideLetters(\n")
    }

    @Test
    fun deprecatedAliasesDifferingOnlyByCaseAreGenerated() {
        generateIconFile(
            """
            {
              "version": "1.0.0",
              "icons": {
                "arrow-down-a-z": [{"tag":"path","attrs":{"d":"M1 1"}}]
              },
              "deprecated": {"arrow-down-az":"arrow-down-a-z"}
            }
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("arrow-down-a-z.kt", "deprecated/arrow-down-az.kt")
        assertThat(packageDir.resolve("deprecated/arrow-down-az.kt").readText()).contains("\nfun LucideArrowDownAz(\n")
    }

    @Test
    fun deprecatedAliasesAreSkippedIfTheyShadowAnIconOrPointNowhere() {
        generateIconFile(
            """
            {
              "version": "1.0.0",
              "icons": {
                "grid-2x2": [{"tag":"path","attrs":{"d":"M1 1"}}]
              },
              "deprecated": {"grid2x2":"grid-2x2","gone":"no-such-icon"}
            }
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("grid-2x2.kt")
    }

    @Test
    fun identicalMethodNamesAreRejected() {
        val e = assertThrows<IllegalStateException> {
            generateIconFile(
                """
                {
                  "version": "1.0.0",
                  "icons": {
                    "arrow-1": [{"tag":"path","attrs":{"d":"M1 1"}}],
                    "arrow1": [{"tag":"path","attrs":{"d":"M2 2"}}]
                  },
                  "deprecated": {}
                }
                """.trimIndent(),
                IconVisibility.PUBLIC,
            )
        }
        assertThat(e.message!!).contains("LucideArrow1=[arrow-1, arrow1]")
    }

    @Test
    fun staleFilesAreRemoved() {
        packageDir.mkdirs()
        packageDir.resolve("removed-icon.kt").writeText("// stale")

        generateIconFile(
            """
            {
              "version": "1.0.0",
              "icons": {
                "house": [{"tag":"path","attrs":{"d":"M1 1"}}]
              },
              "deprecated": {}
            }
            """.trimIndent(),
            IconVisibility.PUBLIC,
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("house.kt")
    }
}
