package com.varabyte.kobweb.icons.codegen

import java.io.File

/**
 * Google's Material Symbols (https://developers.google.com/fonts/docs/material_symbols), rendered with its icon fonts.
 *
 * Its version is a commit in https://github.com/google/material-design-icons, which has no release tags.
 *
 * The icons file lists one icon name per line, after a couple of comment lines:
 * ```
 * # ...
 * 10k
 * 10mp
 * ...
 * ```
 *
 * Each icon becomes a composable that renders it, e.g. `MsArrowBack`.
 */
class MsIconSet : IconSet {
    override val id = "ms"

    override fun fetch(version: String, iconsFile: File) {
        // Material Symbols ships the same set of icons across all of its styles (outlined, rounded, sharp), so we only
        // need a single list of names. We still fetch every family, though, to verify that assumption holds.
        val repo = MaterialDesignIconsRepo(commit = version)
        val namesByFamily = FAMILIES.associateWith { family ->
            repo.fetchCodepointNames("variablefont/$family$AXIS_SUFFIX.codepoints")
        }

        iconsFile.writeText(iconsFileTextFor(version, namesByFamily))
        println("Wrote ${iconsFile.name}")
    }

    /**
     * Converts the icon names listed in each Material Symbols font family (e.g. "MaterialSymbolsOutlined") into the
     * contents of our icons file.
     */
    internal fun iconsFileTextFor(version: String, namesByFamily: Map<String, List<String>>): String {
        val (primaryFamily, names) = namesByFamily.entries.first()
        namesByFamily.forEach { (family, familyNames) ->
            if (familyNames.toSet() != names.toSet()) {
                val missing = names - familyNames.toSet()
                val extra = familyNames - names.toSet()
                error(
                    "Icon names for $family differ from $primaryFamily, but this task assumes they are the same. " +
                        "Missing: ${missing.take(10)}${if (missing.size > 10) " (+${missing.size - 10} more)" else ""}, " +
                        "extra: ${extra.take(10)}${if (extra.size > 10) " (+${extra.size - 10} more)" else ""}"
                )
            }
        }

        return buildString {
            appendLine("# See the README.md for more information about this file. It is parsed by this project's generateIcons gradle task.")
            appendLine("# Generated by the fetchIcons task from google/material-design-icons @ $version")
            names.forEach { appendLine(it) }
        }
    }

    override fun generateBindings(iconsFile: File, options: IconCodegenOptions, outputDir: File) {
        val iconRawNames = iconsFile
            .readLines()
            .map { it.trim() }
            .filter { line -> !line.startsWith("#") && line.isNotBlank() }
            // Some icons have aliases that differ only by underscores (e.g. "print_shop" and "printshop"), which would
            // generate near-identical method names (e.g. MsPrintShop and MsPrintshop). Keep only the longest version
            // of each name, since its underscores give us more readable method names.
            .groupBy { it.replace("_", "") }
            .map { (_, values) -> values.maxBy { it.length } }

        iconRawNames.requireUniqueMethodNames { it.toMethodName() }

        val visibility = options.visibility.modifierPrefix
        val iconsHeader =
            """
            |//@formatter:off
            |@file:Suppress("unused", "SpellCheckingInspection")
            |
            |// !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
            |// THIS FILE IS AUTOGENERATED.
            |//
            |// Do not edit this file by hand. Instead, update `${iconsFile.name}` in the module root (via the
            |// `fetchIcons` Gradle task) and run the Gradle task "generateIcons".
            |// !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
            |
            |package ${options.packageName}
            |
            |import androidx.compose.runtime.*
            |import com.varabyte.kobweb.compose.ui.Modifier
            |import ${options.packageName}.IconStyle.*
            |
            """.trimMargin()

        val packageDir = outputDir.preparePackageDir(options.packageName)

        packageDir.resolve("_MsIcon.kt").writeText(
            iconsHeader + $$"""
            |import com.varabyte.kobweb.compose.ui.toAttrs
            |import org.jetbrains.compose.web.dom.Span
            |import org.jetbrains.compose.web.dom.Text
            |
            |$${visibility}enum class IconStyle {
            |    OUTLINED,
            |    ROUNDED,
            |    SHARP;
            |}
            |
            |@Deprecated("Use IconStyle instead", ReplaceWith("IconStyle"))
            |$${visibility}typealias MsIconStyle = IconStyle
            |
            |private fun IconStyle.toClassNameSuffix(): String {
            |    return when (this) {
            |        OUTLINED -> "-outlined"
            |        ROUNDED -> "-rounded"
            |        SHARP -> "-sharp"
            |    }
            |}
            |
            |@Composable
            |$${visibility}fun MsIcon(
            |    name: String,
            |    modifier: Modifier,
            |    style: IconStyle = OUTLINED,
            |) {
            |    Span(
            |        attrs = modifier.toAttrs { classes("material-symbols${style.toClassNameSuffix()}") }
            |    ) {
            |        Text(name)
            |    }
            |}
            |
            """.trimMargin()
        )

        for (rawName in iconRawNames) {
            val iconCode = "@Composable ${visibility}fun ${rawName.toMethodName()}(modifier: Modifier = Modifier, style: IconStyle = OUTLINED) = MsIcon(\"$rawName\", modifier, style)"

            // Name files after the raw icon name, not the method name. Method names can differ only by case, which
            // collides on case-insensitive file systems and is rejected by the Kotlin/JS compiler.
            packageDir.resolve("$rawName.kt").writeText("$iconsHeader\n$iconCode")
        }
    }

    /** Converts a raw icon name to its method name, e.g. "arrow_back" -> "MsArrowBack". */
    private fun String.toMethodName() = "Ms" + split("_").joinToString("") { part -> part.replaceFirstChar { it.uppercase() } }

    companion object {
        private val FAMILIES = listOf(
            "MaterialSymbolsOutlined",
            "MaterialSymbolsRounded",
            "MaterialSymbolsSharp",
        )

        /** URL-encoded axis suffix in the codepoints file names: [FILL,GRAD,opsz,wght] */
        private const val AXIS_SUFFIX = "%5BFILL%2CGRAD%2Copsz%2Cwght%5D"
    }
}
