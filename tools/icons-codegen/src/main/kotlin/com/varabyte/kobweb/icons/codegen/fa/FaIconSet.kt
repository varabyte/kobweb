package com.varabyte.kobweb.icons.codegen.fa

import com.varabyte.kobweb.icons.codegen.IconCodegenOptions
import com.varabyte.kobweb.icons.codegen.IconSet
import com.varabyte.kobweb.icons.codegen.modifierPrefix
import com.varabyte.kobweb.icons.codegen.fetch.GitHubRepo
import com.varabyte.kobweb.icons.codegen.fetch.VersionSpec
import com.varabyte.kobweb.icons.codegen.generate.AutogeneratedNotice
import com.varabyte.kobweb.icons.codegen.generate.checkUnique
import com.varabyte.kobweb.icons.codegen.generate.IconMethodNamer
import com.varabyte.kobweb.icons.codegen.generate.preparePackageDir
import com.varabyte.kobweb.icons.codegen.stylesheet.IconStylesheet
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.io.File

/**
 * Font Awesome's free icons (https://fontawesome.com), rendered with its icon font.
 *
 * The icons file lists icon names per category, one category per line:
 * ```
 * fas=0,1,2,...,address-book,...
 * far=address-book,...
 * fab=42-group,500px,...
 * ```
 *
 * where `fas`, `far`, and `fab` are Font Awesome's short style prefixes for its solid, regular, and brand icons. Each
 * icon becomes a composable that renders it, e.g. `FaAddressBook`.
 */
class FaIconSet : IconSet {
    override val id = "fa"

    /**
     * Font Awesome's free icon categories.
     *
     * @property shortPrefix Font Awesome's short style prefix for the category (e.g. "fas"), which is also its CSS
     *   class and its key in the icons file.
     * @property styleName Font Awesome's name for the category's style (e.g. "solid"), as used in
     *   `metadata/icons.json`.
     */
    enum class Category(val shortPrefix: String, val styleName: String) {
        SOLID("fas", "solid"),
        REGULAR("far", "regular"),
        BRAND("fab", "brands"),
    }

    override fun resolveVersion(spec: String) = gitHubRepo.resolveRelease(VersionSpec(spec))

    override val stylesheet = object : IconStylesheet {
        override fun urlFor(version: String) = "https://cdnjs.cloudflare.com/ajax/libs/font-awesome/$version/css/all.min.css"

        override fun versionFor(versions: Collection<String>) = versions.maxWith(VersionSpec.RELEASE_ORDER)

        /**
         * Font Awesome follows semantic versioning, so a stylesheet still has every icon from older releases with the
         * same major version, but a new major version may rename or remove some.
         */
        override fun serves(stylesheetVersion: String, bindingsVersion: String): Boolean {
            return stylesheetVersion.substringBefore('.') == bindingsVersion.substringBefore('.') &&
                VersionSpec.RELEASE_ORDER.compare(stylesheetVersion, bindingsVersion) >= 0
        }
    }

    override fun fetch(version: String, iconsFile: File) {
        val iconsJson = gitHubRepo.fetchFileText(version, "metadata/icons.json")

        iconsFile.writeText(iconsFileTextFor(version, iconsJson))
        println("Wrote ${iconsFile.name}")
    }

    /** Converts the contents of Font Awesome's `metadata/icons.json` file into the contents of our icons file. */
    internal fun iconsFileTextFor(version: String, iconsJson: String): String {
        // Each entry lists the styles available for free, e.g. "address-book": {"free": ["solid", "regular"], ...}
        val freeStyles: Map<String, Set<String>> = Json.parseToJsonElement(iconsJson).jsonObject
            .mapValues { (_, icon) ->
                icon.jsonObject["free"]?.jsonArray?.map { it.jsonPrimitive.content }?.toSet().orEmpty()
            }
            // Generated functions can either pick between solid and regular styles or render a brand, not both. In
            // practice, only the "font-awesome" icon is a brand that also has other styles.
            .mapValues { (_, styles) ->
                if (styles.size > 1) styles - Category.BRAND.styleName else styles
            }

        return buildString {
            appendLine(AutogeneratedNotice.IconsFile("FortAwesome/Font-Awesome @ $version").text)
            for (category in Category.entries) {
                val names = freeStyles.filterValues { category.styleName in it }.keys
                appendLine("${category.shortPrefix}=${names.joinToString(",")}")
            }
        }
    }

    override fun generateBindings(iconsFile: File, options: IconCodegenOptions, outputDir: File) {
        // {SOLID=[ad, address-book, address-card, ...], REGULAR=[address-book, address-card, angry, ...], ... }
        val iconRawNames = iconsFile
            .readLines()
            .filter { line -> !line.startsWith("#") }
            .associate { line ->
                val (shortPrefix, names) = line.split("=", limit = 2)
                val category = Category.entries.find { it.shortPrefix == shortPrefix }
                    ?: error("Unexpected category string: $shortPrefix")

                category to names
                    .split(",")
                    .filter { it.isNotEmpty() }
                    // Some icons have aliases that differ only by dashes (e.g. "print-shop" and "printshop"), which
                    // would generate near-identical method names (e.g. FaPrintShop and FaPrintshop). Keep only the
                    // longest version of each name, since its dashes give us more readable method names.
                    .groupBy { it.replace("-", "") }
                    .map { (_, values) -> values.maxBy { it.length } }
            }

        // For each icon name, figure out what categories they are in. This will affect the function signature we
        // generate, e.g. {ad=[SOLID], address-book=[SOLID, REGULAR], address-card=[SOLID, REGULAR], ...}
        val iconCategories = mutableMapOf<String, MutableSet<Category>>()
        iconRawNames.forEach { (category, rawNames) ->
            rawNames.forEach { rawName -> iconCategories.getOrPut(rawName) { mutableSetOf() }.add(category) }
        }

        val invalidGroupings = iconCategories.filterNot { (_, categories) ->
            categories.size == 1 || categories == setOf(Category.SOLID, Category.REGULAR)
        }
        check(invalidGroupings.isEmpty()) {
            "Found unexpected groupings. An icon should only be in its own category OR it can have solid and regular versions: $invalidGroupings"
        }

        methodNamer.checkUnique(iconCategories.keys)

        val visibility = options.modifierPrefix
        val iconsHeader =
            """
            |${AutogeneratedNotice.Bindings(iconsFile).text}
            |//@formatter:off
            |@file:Suppress("unused", "SpellCheckingInspection")
            |
            |package ${options.packageName}
            |
            |import androidx.compose.runtime.*
            |import com.varabyte.kobweb.compose.ui.Modifier
            |
            """.trimMargin()

        val packageDir = options.preparePackageDir(outputDir)

        packageDir.resolve("_FaIcon.kt").writeText(
            iconsHeader + $$"""
            |import com.varabyte.kobweb.compose.ui.toAttrs
            |import org.jetbrains.compose.web.dom.Span
            |
            |$${visibility}enum class FaIconCategory(internal val className: String) {
            |    REGULAR("far"),
            |    SOLID("fas"),
            |    BRAND("fab");
            |}
            |
            |$${visibility}enum class FaIconStyle(internal val category: FaIconCategory) {
            |    FILLED(FaIconCategory.SOLID),
            |    OUTLINE(FaIconCategory.REGULAR);
            |}
            |
            |// See: https://fontawesome.com/docs/web/style/size
            |$${visibility}enum class FaIconSize(internal val className: String) {
            |    // Relative sizes
            |    XXS("fa-2xs"),
            |    XS("fa-xs"),
            |    SM("fa-sm"),
            |    LG("fa-lg"),
            |    XL("fa-xl"),
            |    XXL("fa-2xl"),
            |
            |    // Literal sizes
            |    X1("fa-1x"),
            |    X2("fa-2x"),
            |    X3("fa-3x"),
            |    X4("fa-4x"),
            |    X5("fa-5x"),
            |    X6("fa-6x"),
            |    X7("fa-7x"),
            |    X8("fa-8x"),
            |    X9("fa-9x"),
            |    X10("fa-10x");
            |}
            |
            |@Composable
            |$${visibility}fun FaIcon(
            |    name: String,
            |    modifier: Modifier,
            |    style: FaIconCategory = FaIconCategory.REGULAR,
            |    size: FaIconSize? = null,
            |) {
            |    Span(
            |        attrs = modifier.toAttrs {
            |            classes(style.className, "fa-$name")
            |            if (size != null) {
            |                classes(size.className)
            |            }
            |        }
            |    )
            |}
            |
            |@Deprecated("Use FaIconCategory instead", ReplaceWith("FaIconCategory"))
            |$${visibility}typealias IconCategory = FaIconCategory
            |
            |@Deprecated("Use FaIconStyle instead", ReplaceWith("FaIconStyle"))
            |$${visibility}typealias IconStyle = FaIconStyle
            |
            |@Deprecated("Use FaIconSize instead", ReplaceWith("FaIconSize"))
            |$${visibility}typealias IconSize = FaIconSize
            |
            """.trimMargin()
        )

        for ((rawName, categories) in iconCategories) {
            val methodName = methodNamer.methodNameFor(rawName)
            val iconCode = when {
                categories.size == 2 -> {
                    "@Composable ${visibility}fun $methodName(modifier: Modifier = Modifier, style: FaIconStyle = FaIconStyle.OUTLINE, size: FaIconSize? = null) = FaIcon(\"$rawName\", modifier, style.category, size)"
                }

                else -> {
                    val category = categories.single()
                    "@Composable ${visibility}fun $methodName(modifier: Modifier = Modifier, size: FaIconSize? = null) = FaIcon(\"$rawName\", modifier, FaIconCategory.${category.name}, size)"
                }
            }

            // Name files after the raw icon name, not the method name. Method names can differ only by case, which
            // collides on case-insensitive file systems and is rejected by the Kotlin/JS compiler.
            packageDir.resolve("$rawName.kt").writeText("$iconsHeader\n$iconCode")
        }
    }

    private val gitHubRepo = GitHubRepo("FortAwesome/Font-Awesome")

    private val methodNamer = IconMethodNamer(prefix = "Fa", separator = '-')
}
