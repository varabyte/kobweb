@file:Suppress("SpellCheckingInspection")

package com.varabyte.kobweb.icons.codegen.material

import com.varabyte.kobweb.icons.model.ms.MsIconSet
import com.varabyte.truthish.assertThat
import com.varabyte.truthish.assertThrows
import org.junit.Test
import java.io.File
import kotlin.io.path.createTempDirectory

class MsCodegenTest {
    private val rootDir = createTempDirectory("ms-icon-set-test").toFile().also { it.deleteOnExit() }
    private val iconsFile = rootDir.resolve("ms-icon-list.txt")
    private val outDir = rootDir.resolve("out")
    private val packageDir = outDir.resolve("test/icons")

    private fun generateBindings(iconsText: String) {
        iconsFile.writeText(iconsText)
        MsCodegen().generateBindings(iconsFile, "test.icons", outDir)
    }

    private fun File.relativeFilePaths() = walkTopDown().filter { it.isFile }.map { it.relativeTo(this).path }.sorted().toList()

    @Test
    fun iconsFileListsNamesOnce() {
        val iconsText = MsCodegen().iconsFileTextFor(
            "abc123",
            mapOf(
                MsIconSet.Style.OUTLINED to listOf("arrow_back", "home"),
                MsIconSet.Style.ROUNDED to listOf("home", "arrow_back"),
            )
        )

        assertThat(iconsText).isEqualTo(
            """
            # THIS FILE IS AUTOGENERATED from google/material-design-icons @ abc123. Fetch it again instead of editing it by hand.
            arrow_back
            home

            """.trimIndent()
        )
    }

    @Test
    fun stylesWithDifferentIconsAreRejected() {
        val e = assertThrows<IllegalStateException> {
            MsCodegen().iconsFileTextFor(
                "abc123",
                mapOf(
                    MsIconSet.Style.OUTLINED to listOf("arrow_back", "home"),
                    MsIconSet.Style.ROUNDED to listOf("home"),
                )
            )
        }
        assertThat(e.message!!).contains("Icon names for MaterialSymbolsRounded differ from MaterialSymbolsOutlined")
    }

    @Test
    fun generatesIconFile() {
        generateBindings(
            """
            # A comment
            arrow_back
            """.trimIndent(),
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_MsIcon.kt", "arrow_back.kt")
        assertThat(packageDir.resolve("arrow_back.kt").readText()).isEqualTo(
            """
            // THIS FILE IS AUTOGENERATED from `ms-icon-list.txt`. Do not edit it by hand.
            //@formatter:off
            @file:Suppress("unused", "SpellCheckingInspection")

            package test.icons

            import androidx.compose.runtime.*
            import com.varabyte.kobweb.compose.ui.Modifier
            import test.icons.MsIconStyle.*

            @Composable fun MsArrowBack(modifier: Modifier = Modifier, style: MsIconStyle = OUTLINED) = MsIcon("arrow_back", modifier, style)
            """.trimIndent()
        )
    }

    @Test
    fun namesDifferingOnlyByUnderscoresKeepTheLongestOne() {
        generateBindings(
            """
            add_chart
            addchart
            """.trimIndent(),
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_MsIcon.kt", "add_chart.kt")
    }
}
