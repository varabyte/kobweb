package com.varabyte.kobweb.icons.codegen.material

import com.varabyte.truthish.assertThat
import com.varabyte.truthish.assertThrows
import org.junit.Test
import java.io.File
import kotlin.io.path.createTempDirectory

class MdiCodegenTest {
    private val rootDir = createTempDirectory("mdi-icon-set-test").toFile().also { it.deleteOnExit() }
    private val iconsFile = rootDir.resolve("md-icon-list.txt")
    private val outDir = rootDir.resolve("out")
    private val packageDir = outDir.resolve("test/icons")

    private fun generateBindings(iconsText: String) {
        iconsFile.writeText(iconsText)
        MdiCodegen().generateBindings(iconsFile, "test.icons", outDir)
    }

    private fun File.relativeFilePaths() = walkTopDown().filter { it.isFile }.map { it.relativeTo(this).path }.sorted().toList()

    @Test
    fun generatesIconFile() {
        generateBindings(
            """
            # A comment
            mdi=home
            mdio=home
            mdir=home
            mdis=home
            mdit=home
            """.trimIndent(),
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_MdiIcon.kt", "home.kt")
        assertThat(packageDir.resolve("home.kt").readText()).isEqualTo(
            """
            // THIS FILE IS AUTOGENERATED from `md-icon-list.txt`. Do not edit it by hand.
            //@formatter:off
            @file:Suppress("unused", "SpellCheckingInspection")

            package test.icons

            import androidx.compose.runtime.*
            import com.varabyte.kobweb.compose.ui.Modifier
            import test.icons.MdiIconStyle.*

            @Composable fun MdiHome(modifier: Modifier = Modifier, style: MdiIconStyle = FILLED) = MdiIcon("home", modifier, style)
            """.trimIndent()
        )
    }

    @Test
    fun iconsInOneStyleTakeNoStyleParameter() {
        generateBindings(
            """
            mdi=
            mdio=
            mdir=
            mdis=
            mdit=tonality
            """.trimIndent(),
        )

        assertThat(packageDir.resolve("tonality.kt").readText()).endsWith(
            "\n@Composable fun MdiTonality(modifier: Modifier = Modifier) = MdiIcon(\"tonality\", modifier, TWO_TONED)"
        )
    }

    @Test
    fun iconsInSomeStylesAssertTheStyleParameter() {
        generateBindings(
            """
            mdi=
            mdio=label
            mdir=label
            mdis=
            mdit=
            """.trimIndent(),
        )

        assertThat(packageDir.resolve("label.kt").readText()).endsWith(
            "\n@Composable fun MdiLabel(modifier: Modifier = Modifier, style: MdiIconStyle = OUTLINED) = MdiIcon(\"label\", modifier, style.also { it.assertValidStyle(\"MdiLabel\", OUTLINED, ROUNDED) })"
        )
    }

    @Test
    fun stylesHaveTheirCssClasses() {
        generateBindings(
            """
            mdi=home
            mdio=
            mdir=
            mdis=
            mdit=
            """.trimIndent(),
        )

        val sharedText = packageDir.resolve("_MdiIcon.kt").readText()
        assertThat(sharedText).contains(
            """
            enum class MdiIconStyle(internal val className: String) {
                FILLED("material-icons"),
                OUTLINED("material-icons-outlined"),
                ROUNDED("material-icons-round"),
                SHARP("material-icons-sharp"),
                TWO_TONED("material-icons-two-tone");
            }
            """.trimIndent()
        )
        assertThat(sharedText).contains("attrs = modifier.toAttrs { classes(style.className) }")
    }

    @Test
    fun iconsInTheWrongStyleFailWhenRendered() {
        generateBindings(
            """
            mdi=home
            mdio=
            mdir=
            mdis=
            mdit=
            """.trimIndent(),
        )

        assertThat(packageDir.resolve("_MdiIcon.kt").readText()).contains(
            $$"""
            internal fun MdiIconStyle.assertValidStyle(methodName: String, vararg validStyles: MdiIconStyle) {
                if (this !in validStyles) {
                    error("Attempted to render \"$methodName\" with style $this. Must be one of: ${validStyles.joinToString()}")
                }
            }
            """.trimIndent()
        )
    }

    @Test
    fun legacyNamesAreDeprecatedAliases() {
        generateBindings(
            """
            mdi=home
            mdio=
            mdir=
            mdis=
            mdit=
            """.trimIndent(),
        )

        val sharedText = packageDir.resolve("_MdiIcon.kt").readText()
        assertThat(sharedText).contains(
            """
            @Deprecated("Use MdiIconStyle instead", ReplaceWith("MdiIconStyle"))
            typealias IconStyle = MdiIconStyle
            """.trimIndent()
        )
        assertThat(sharedText).contains(
            """
            @Deprecated("Use MdiIcon instead", ReplaceWith("MdiIcon(name, modifier, style)"))
            @Composable
            fun MdIcon(name: String, modifier: Modifier, style: MdiIconStyle = FILLED) = MdiIcon(name, modifier, style)
            """.trimIndent()
        )
    }

    @Test
    fun unknownStyleKeysAreRejected() {
        val e = assertThrows<IllegalStateException> {
            generateBindings(
                """
                mdi=home
                mdix=home
                """.trimIndent(),
            )
        }
        assertThat(e.message!!).isEqualTo("Unexpected style grouping: mdix")
    }

    @Test
    fun stylesheetUrlLoadsEveryStyle() {
        assertThat(MdiCodegen().stylesheetUrl("abc123")).isEqualTo(
            "https://fonts.googleapis.com/css2?family=Material+Icons&family=Material+Icons+Outlined&family=Material+Icons+Round&family=Material+Icons+Sharp&family=Material+Icons+Two+Tone"
        )
    }

    @Test
    fun namesDifferingOnlyByUnderscoresKeepTheLongestOne() {
        generateBindings(
            """
            mdi=add_chart,addchart
            mdio=
            mdir=
            mdis=
            mdit=
            """.trimIndent(),
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_MdiIcon.kt", "add_chart.kt")
    }
}
