@file:Suppress("SpellCheckingInspection")

package com.varabyte.kobweb.icons.codegen.fa

import com.varabyte.truthish.assertThat
import com.varabyte.truthish.assertThrows
import org.junit.Test
import java.io.File
import kotlin.io.path.createTempDirectory

class FaCodegenTest {
    private val rootDir = createTempDirectory("fa-icon-set-test").toFile().also { it.deleteOnExit() }
    private val iconsFile = rootDir.resolve("fa-icon-list.txt")
    private val outDir = rootDir.resolve("out")
    private val packageDir = outDir.resolve("test/icons")

    private fun generateBindings(iconsText: String) {
        iconsFile.writeText(iconsText)
        FaCodegen().generateBindings(iconsFile, "test.icons", outDir)
    }

    private fun File.relativeFilePaths() = walkTopDown().filter { it.isFile }.map { it.relativeTo(this).path }.sorted().toList()

    @Test
    fun iconsFileListsFreeIconsPerStyle() {
        val iconsText = FaCodegen().iconsFileTextFor(
            "6.5.2",
            """
            {
              "address-book": {"label": "Address Book", "unicode": "f2b9", "free": ["solid", "regular"]},
              "bell": {"label": "Bell", "unicode": "f0f3", "free": ["solid"]},
              "github": {"label": "GitHub", "unicode": "f09b", "free": ["brands"]},
              "font-awesome": {"label": "Font Awesome", "unicode": "f2b4", "free": ["brands", "solid", "regular"]}
            }
            """.trimIndent()
        )

        assertThat(iconsText).isEqualTo(
            """
            # THIS FILE IS AUTOGENERATED from FortAwesome/Font-Awesome @ 6.5.2. Fetch it again instead of editing it by hand.
            fas=address-book,bell,font-awesome
            far=address-book,font-awesome
            fab=github

            """.trimIndent()
        )
    }

    @Test
    fun generatesIconFilesPerStyle() {
        generateBindings(
            """
            # A comment
            fas=address-book,bell
            far=address-book
            fab=github
            """.trimIndent(),
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_FaIcon.kt", "address-book.kt", "bell.kt", "github.kt")
        assertThat(packageDir.resolve("address-book.kt").readText()).isEqualTo(
            """
            // THIS FILE IS AUTOGENERATED from `fa-icon-list.txt`. Do not edit it by hand.
            //@formatter:off
            @file:Suppress("unused", "SpellCheckingInspection")

            package test.icons

            import androidx.compose.runtime.*
            import com.varabyte.kobweb.compose.ui.Modifier

            @Composable fun FaAddressBook(modifier: Modifier = Modifier, style: FaIconStyle = FaIconStyle.REGULAR, size: FaIconSize? = null) = FaIcon("address-book", modifier, style, size)
            """.trimIndent()
        )
        assertThat(packageDir.resolve("bell.kt").readText()).endsWith(
            "\n@Composable fun FaBell(modifier: Modifier = Modifier, size: FaIconSize? = null) = FaIcon(\"bell\", modifier, FaIconStyle.SOLID, size)"
        )
        assertThat(packageDir.resolve("github.kt").readText()).endsWith(
            "\n@Composable fun FaGithub(modifier: Modifier = Modifier, size: FaIconSize? = null) = FaBrandIcon(\"github\", modifier, size)"
        )
    }

    @Test
    fun stylesHaveTheirCssClasses() {
        generateBindings(
            """
            fas=bell
            far=
            fab=
            """.trimIndent(),
        )

        assertThat(packageDir.resolve("_FaIcon.kt").readText()).contains(
            """
            enum class FaIconStyle(internal val className: String) {
                SOLID("fas"),
                REGULAR("far");
            }
            """.trimIndent()
        )
    }

    @Test
    fun sizesHaveTheirCssClasses() {
        generateBindings(
            """
            fas=bell
            far=
            fab=
            """.trimIndent(),
        )

        assertThat(packageDir.resolve("_FaIcon.kt").readText()).contains(
            """
            enum class FaIconSize(internal val className: String) {
                // Relative sizes
                XXS("fa-2xs"),
                XS("fa-xs"),
                SM("fa-sm"),
                LG("fa-lg"),
                XL("fa-xl"),
                XXL("fa-2xl"),

                // Literal sizes
                X1("fa-1x"),
                X2("fa-2x"),
                X3("fa-3x"),
                X4("fa-4x"),
                X5("fa-5x"),
                X6("fa-6x"),
                X7("fa-7x"),
                X8("fa-8x"),
                X9("fa-9x"),
                X10("fa-10x");
            }
            """.trimIndent()
        )
    }

    @Test
    fun iconsRenderAsSpansWithStyleNameAndSizeClasses() {
        generateBindings(
            """
            fas=bell
            far=
            fab=github
            """.trimIndent(),
        )

        val sharedText = packageDir.resolve("_FaIcon.kt").readText()
        assertThat(sharedText).contains(
            """
            @Composable
            fun FaIcon(
                name: String,
                modifier: Modifier,
                style: FaIconStyle = FaIconStyle.REGULAR,
                size: FaIconSize? = null,
            ) {
                FaIconSpan(style.className, name, modifier, size)
            }

            @Composable
            fun FaBrandIcon(
                name: String,
                modifier: Modifier,
                size: FaIconSize? = null,
            ) {
                FaIconSpan("fab", name, modifier, size)
            }
            """.trimIndent()
        )
        assertThat(sharedText).contains(
            $$"""
            @Composable
            private fun FaIconSpan(styleClassName: String, name: String, modifier: Modifier, size: FaIconSize?) {
                Span(
                    attrs = modifier.toAttrs {
                        classes(styleClassName, "fa-$name")
                        if (size != null) {
                            classes(size.className)
                        }
                    }
                )
            }
            """.trimIndent()
        )
    }

    @Test
    fun legacyNamesAreDeprecatedAliases() {
        generateBindings(
            """
            fas=bell
            far=
            fab=
            """.trimIndent(),
        )

        val sharedText = packageDir.resolve("_FaIcon.kt").readText()
        assertThat(sharedText).contains(
            """
            @Deprecated("Use FaIconStyle instead", ReplaceWith("FaIconStyle"))
            object IconStyle {
                @Deprecated("Use FaIconStyle.SOLID instead", ReplaceWith("FaIconStyle.SOLID"))
                val FILLED = FaIconStyle.SOLID

                @Deprecated("Use FaIconStyle.REGULAR instead", ReplaceWith("FaIconStyle.REGULAR"))
                val OUTLINE = FaIconStyle.REGULAR
            }
            """.trimIndent()
        )
        assertThat(sharedText).contains(
            """
            @Deprecated("Use FaIconSize instead", ReplaceWith("FaIconSize"))
            typealias IconSize = FaIconSize
            """.trimIndent()
        )
    }

    @Test
    fun unknownStylePrefixesAreRejected() {
        val e = assertThrows<IllegalStateException> {
            generateBindings(
                """
                fas=bell
                fal=bell
                """.trimIndent(),
            )
        }
        assertThat(e.message!!).isEqualTo("Unexpected style prefix: fal")
    }

    @Test
    fun namesDifferingOnlyByDashesKeepTheLongestOne() {
        generateBindings(
            """
            fas=print-shop,printshop
            far=
            fab=
            """.trimIndent(),
        )

        assertThat(packageDir.relativeFilePaths()).containsExactly("_FaIcon.kt", "print-shop.kt")
    }

    @Test
    fun stylesheetUrlFollowsVersion() {
        assertThat(FaCodegen().stylesheetUrl("6.5.2"))
            .isEqualTo("https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2/css/all.min.css")
    }

    @Test
    fun brandsWithOtherStylesAreRejected() {
        val e = assertThrows<IllegalStateException> {
            generateBindings(
                """
                fas=font-awesome
                far=
                fab=font-awesome
                """.trimIndent(),
            )
        }
        assertThat(e.message!!).contains("Found unexpected groupings")
    }
}
