package com.varabyte.kobweb.icons.codegen.lucide

import com.varabyte.kobweb.icons.codegen.IconSetCodegen
import com.varabyte.kobweb.icons.codegen.fetch.GitHubRepo
import com.varabyte.kobweb.icons.codegen.generate.AutogeneratedNotice
import com.varabyte.kobweb.icons.codegen.generate.checkUnique
import com.varabyte.kobweb.icons.codegen.generate.preparePackageDir
import com.varabyte.kobweb.icons.model.lucide.LucideIconSet
import com.varabyte.kobweb.icons.parsers.lucide.LucideIcons
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.io.File

/**
 * Lucide icons (https://lucide.dev), rendered as inline SVG.
 *
 * The icons file is JSON that looks like:
 * ```
 * {
 *   "version": "1.6.0",
 *   "icons": {
 *     "arrow-right": [{"tag":"path","attrs":{"d":"M5 12h14"}},{"tag":"path","attrs":{"d":"m12 5 7 7-7 7"}}],
 *     ...
 *   },
 *   "renamed": {"old-name":"new-name", ...},
 *   "deprecated": ["badge-euro", ...]
 * }
 * ```
 *
 * Each icon becomes a composable that draws its SVG elements, e.g. `LucideArrowRight`, and each old name in `renamed`
 * becomes a deprecated alias for the icon that replaced it. Icons that Lucide has deprecated outright, with no
 * replacement, are listed in `deprecated` and their composables are marked deprecated.
 */
class LucideCodegen : IconSetCodegen {
    override val id = "lucide"

    private val gitHubRepo = GitHubRepo(LucideIconSet.gitHubRepo)

    override fun fetch(version: String, iconsFile: File) {
        val icons = LucideIcons.parseRepoZip(gitHubRepo.openTagArchiveStream(version)).icons

        // Deprecated aliases are old names that an icon was renamed from
        val renamedIcons = icons.entries
            .flatMap { (iconName, icon) -> icon.aliases.filter { it.isDeprecated }.map { it.name to iconName } }
            .toMap()

        iconsFile.bufferedWriter().use { writer ->
            writer.write("{\n")
            writer.write("  \"version\": \"$version\",\n")

            writer.write("  \"icons\": {\n")
            val sortedIcons = icons.keys.sorted()
            sortedIcons.forEachIndexed { index, iconName ->
                val elements = icons.getValue(iconName).elements
                writer.write("    \"${jsonEscape(iconName)}\": [")
                elements.forEachIndexed { elemIndex, (tag, attributes) ->
                    writer.write("{\"tag\":\"${jsonEscape(tag)}\"")
                    if (attributes.isNotEmpty()) {
                        writer.write(",\"attrs\":{")
                        attributes.entries.forEachIndexed { attrIndex, (key, value) ->
                            writer.write("\"${jsonEscape(key)}\":\"${jsonEscape(value)}\"")
                            if (attrIndex < attributes.size - 1) writer.write(",")
                        }
                        writer.write("}")
                    }
                    writer.write("}")
                    if (elemIndex < elements.size - 1) writer.write(",")
                }
                writer.write("]")
                if (index < sortedIcons.size - 1) writer.write(",")
                writer.write("\n")
            }
            writer.write("  },\n")

            writer.write("  \"renamed\": {")
            val sortedOldNames = renamedIcons.keys.sorted()
            sortedOldNames.forEachIndexed { index, oldName ->
                writer.write("\"${jsonEscape(oldName)}\":\"${jsonEscape(renamedIcons.getValue(oldName))}\"")
                if (index < sortedOldNames.size - 1) writer.write(",")
            }
            writer.write("},\n")

            val deprecatedIconNames = icons.filterValues { it.isDeprecated }.keys.sorted()
            writer.write("  \"deprecated\": [")
            writer.write(deprecatedIconNames.joinToString(",") { "\"${jsonEscape(it)}\"" })
            writer.write("]\n")

            writer.write("}\n")
        }
        println("Written ${icons.size} icons to ${iconsFile.name}")
    }

    override fun generateBindings(iconsFile: File, packageName: String, outputDir: File) {
        val json = Json.parseToJsonElement(iconsFile.readText()).jsonObject

        val activeIcons: Map<String, List<ElementInfo>> = json.getValue("icons").jsonObject
            .mapValues { (_, elements) ->
                elements.jsonArray.map { element ->
                    val elementObj = element.jsonObject
                    val tag = elementObj.getValue("tag").jsonPrimitive.content
                    val attrs = elementObj["attrs"]?.jsonObject
                        ?.mapValues { (_, value) -> value.jsonPrimitive.content }
                        .orEmpty()
                    ElementInfo.from(tag, attrs)
                }
            }
        val renamedIcons: Map<String, String> = json["renamed"]?.jsonObject
            ?.mapValues { (_, canonicalName) -> canonicalName.jsonPrimitive.content }
            .orEmpty()
        val deprecatedIconNames: Set<String> = json["deprecated"]?.jsonArray
            ?.map { it.jsonPrimitive.content }
            ?.toSet()
            .orEmpty()

        val methodNamer = LucideIconSet.methodNamer
        val activeMethodNames = activeIcons.keys.map { methodNamer.nameFor(it) }.toSet()

        // Skip deprecated aliases that share a method name with an active icon, or whose replacement doesn't exist
        val generatedRenamedIcons = renamedIcons.filter { (deprecatedName, canonicalName) ->
            methodNamer.nameFor(deprecatedName) !in activeMethodNames && canonicalName in activeIcons
        }
        methodNamer.checkUnique(activeIcons.keys + generatedRenamedIcons.keys)

        val fileHeader = buildString {
            appendLine(AutogeneratedNotice.Bindings(iconsFile).text)
            appendLine("//@formatter:off")
            appendLine("@file:Suppress(\"unused\", \"SpellCheckingInspection\", \"PackageDirectoryMismatch\")")
            appendLine()
            appendLine("package $packageName")
            appendLine()
        }

        val packageDir = outputDir.preparePackageDir(packageName)

        for ((iconName, elements) in activeIcons.entries.sortedBy { it.key }) {
            val svgImports = elements.map { it.tag }.toSet().sorted().mapNotNull { tag ->
                if (tag in SUPPORTED_TAGS) "import com.varabyte.kobweb.compose.dom.svg.${tag.capitalize()}" else null
            } + listOfNotNull(
                "import com.varabyte.kobweb.compose.dom.svg.SVGFillType".takeIf { elements.any { it.fill != null } }
            )

            val fileContent = buildString {
                appendLine("import androidx.compose.runtime.Composable")
                appendLine("import com.varabyte.kobweb.compose.dom.svg.SVGStrokeLineCap")
                appendLine("import com.varabyte.kobweb.compose.dom.svg.SVGStrokeLineJoin")
                appendLine("import com.varabyte.kobweb.compose.dom.svg.ViewBox")
                appendLine("import com.varabyte.kobweb.compose.ui.Modifier")
                appendLine("import com.varabyte.kobweb.compose.ui.toAttrs")
                appendLine("import com.varabyte.kobweb.silk.components.icons.IconRenderStyle")
                appendLine("import com.varabyte.kobweb.silk.components.icons.createIcon")
                appendLine("import org.jetbrains.compose.web.css.*")
                svgImports.forEach { appendLine(it) }
                appendLine()
                if (iconName in deprecatedIconNames) {
                    appendLine("@Deprecated(\"Lucide has deprecated this icon.\")")
                }
                appendLine("@Composable")
                appendLine("fun ${methodNamer.nameFor(iconName)}(")
                appendLine("$INDENT$ICON_PARAMS,")
                appendLine(") {")
                appendLine("${INDENT}createIcon(")
                appendLine("$INDENT${INDENT}viewBox = ViewBox.sized(24),")
                appendLine("$INDENT${INDENT}renderStyle = IconRenderStyle.Stroke(strokeWidth),")
                appendLine("$INDENT${INDENT}attrs = modifier.toAttrs {")
                appendLine("$INDENT$INDENT${INDENT}strokeLineCap(SVGStrokeLineCap.Round)")
                appendLine("$INDENT$INDENT${INDENT}strokeLineJoin(SVGStrokeLineJoin.Round)")
                appendLine("$INDENT${INDENT}}")
                appendLine("$INDENT) {")
                elements.forEach { appendElement(it) }
                appendLine("$INDENT}")
                appendLine("}")
            }

            // Name files after the raw (kebab-case) icon name, not the method name. Method names can differ only by
            // case (e.g. "letter-s" -> LucideLetterS, "letters" -> LucideLetters), which collides on case-insensitive
            // file systems and is rejected by the Kotlin/JS compiler.
            packageDir.resolve("$iconName.kt").writeText(fileHeader + fileContent)
        }

        val deprecatedDir = packageDir.resolve("deprecated")
        for ((deprecatedName, canonicalName) in generatedRenamedIcons.entries.sortedBy { it.key }) {
            val canonicalMethodName = methodNamer.nameFor(canonicalName)
            val fileContent = buildString {
                appendLine("import androidx.compose.runtime.Composable")
                appendLine("import com.varabyte.kobweb.compose.ui.Modifier")
                appendLine("import org.jetbrains.compose.web.css.*")
                appendLine()
                appendLine("@Deprecated(\"Use $canonicalMethodName instead.\", ReplaceWith(\"$canonicalMethodName(modifier = modifier, strokeWidth = strokeWidth)\"))")
                appendLine("@Composable")
                appendLine("fun ${methodNamer.nameFor(deprecatedName)}(")
                appendLine("$INDENT$ICON_PARAMS,")
                appendLine(") = $canonicalMethodName(modifier = modifier, strokeWidth = strokeWidth)")
            }

            deprecatedDir.mkdirs()
            deprecatedDir.resolve("$deprecatedName.kt").writeText(fileHeader + fileContent)
        }
    }

    /**
     * Parsed SVG element data, separating parsing from code generation.
     *
     * @property fill The `SVGFillType` entry for the element's `fill` attribute, e.g. "CurrentColor", if it has one.
     *   Lucide draws outlines, but fills a few small shapes, like the dots in "chart-scatter".
     */
    private sealed class ElementInfo(val tag: String, val fill: String?) {
        class Path(val d: String, fill: String?) : ElementInfo("path", fill)
        class Simple(tag: String, val attrs: List<Pair<String, String>>, fill: String?) : ElementInfo(tag, fill)
        class Points(tag: String, val points: List<String>, fill: String?) : ElementInfo(tag, fill)
        class Unsupported(tag: String) : ElementInfo(tag, fill = null)

        companion object {
            /** SVG element tags whose attributes we turn into builder calls, mapped to those attribute names. */
            private val SIMPLE_ELEMENT_ATTRS = mapOf(
                "circle" to listOf("cx", "cy", "r"),
                "ellipse" to listOf("cx", "cy", "rx", "ry"),
                "line" to listOf("x1", "y1", "x2", "y2"),
                "rect" to listOf("x", "y", "width", "height", "rx", "ry"),
            )

            /** SVG `fill` keywords, mapped to their `SVGFillType` entries. */
            private val FILL_TYPES = mapOf("currentColor" to "CurrentColor", "none" to "None")

            fun from(tag: String, attributes: Map<String, String>): ElementInfo {
                val fill = attributes["fill"]?.let { value ->
                    FILL_TYPES[value] ?: error("Unsupported `fill` value: tag=$tag, attrs=$attributes")
                }

                if (tag == "path") {
                    return Path(attributes["d"] ?: "", fill)
                }

                SIMPLE_ELEMENT_ATTRS[tag]?.let { attrNames ->
                    val attrs = attrNames.mapNotNull { attr -> attributes[attr]?.let { value -> attr to value } }
                    return Simple(tag, attrs, fill)
                }

                if (tag == "polyline" || tag == "polygon") {
                    val pairs = attributes["points"]?.trim()?.split("\\s+|,".toRegex())?.chunked(2)?.mapNotNull { coords ->
                        if (coords.size == 2) {
                            val x = coords[0].toDoubleOrNull()
                            val y = coords[1].toDoubleOrNull()
                            if (x != null && y != null) "$x to $y" else null
                        } else null
                    } ?: error("Failed to parse `points` attribute: tag=$tag, attrs=$attributes")
                    return Points(tag, pairs, fill)
                }

                return Unsupported(tag)
            }
        }
    }

    private fun StringBuilder.appendElement(element: ElementInfo) {
        val tagCapitalized = element.tag.capitalize()
        when (element) {
            is ElementInfo.Path -> {
                appendLine("$INDENT${INDENT}Path {")
                appendLine("$INDENT$INDENT${INDENT}d(\"${kotlinEscape(element.d)}\")")
                appendFill(element)
                appendLine("$INDENT${INDENT}}")
            }
            is ElementInfo.Simple -> {
                appendLine("$INDENT${INDENT}$tagCapitalized {")
                for ((attr, value) in element.attrs) {
                    appendLine("$INDENT$INDENT${INDENT}$attr($value)")
                }
                appendFill(element)
                appendLine("$INDENT${INDENT}}")
            }
            is ElementInfo.Points -> {
                appendLine("$INDENT${INDENT}$tagCapitalized {")
                if (element.points.isNotEmpty()) {
                    appendLine("$INDENT$INDENT${INDENT}points(${element.points.joinToString(", ")})")
                }
                appendFill(element)
                appendLine("$INDENT${INDENT}}")
            }
            is ElementInfo.Unsupported -> {
                appendLine("$INDENT${INDENT}// Unsupported SVG element: ${element.tag}")
            }
        }
    }

    private fun StringBuilder.appendFill(element: ElementInfo) {
        element.fill?.let { appendLine("$INDENT$INDENT${INDENT}fill(SVGFillType.$it)") }
    }

    private fun String.capitalize() = replaceFirstChar { it.uppercase() }

    private fun jsonEscape(s: String): String = s
        .replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")

    private fun kotlinEscape(s: String): String = s
        .replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("$", "\\$")

    companion object {
        private const val INDENT = "    "
        private const val ICON_PARAMS = "modifier: Modifier = Modifier, strokeWidth: Number = 2"
        private val SUPPORTED_TAGS = setOf("circle", "ellipse", "line", "path", "polygon", "polyline", "rect")
    }
}
