package com.varabyte.kobweb.icons.codegen.material

import com.varabyte.kobweb.icons.codegen.IconSetCodegen
import com.varabyte.kobweb.icons.codegen.generate.AutogeneratedNotice
import com.varabyte.kobweb.icons.codegen.generate.checkUnique
import com.varabyte.kobweb.icons.codegen.generate.preparePackageDir
import com.varabyte.kobweb.icons.model.ms.MsIconSet
import com.varabyte.kobweb.icons.model.ms.MsIconSet.Style
import java.io.File

/**
 * Google's Material Symbols (https://developers.google.com/fonts/docs/material_symbols), rendered with its icon fonts.
 *
 * Its version is a commit in https://github.com/google/material-design-icons, which has no release tags.
 *
 * The icons file lists one icon name per line, after a couple of comment lines:
 * ```
 * # ...
 * 10k
 * 10mp
 * ...
 * ```
 *
 * Each icon becomes a composable that renders it, e.g. `MsArrowBack`.
 */
class MsCodegen : IconSetCodegen {
    override val id = "ms"

    // Google Fonts doesn't version its stylesheets
    override fun stylesheetUrl(version: String) =
        "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined&family=Material+Symbols+Rounded&family=Material+Symbols+Sharp"

    override fun fetch(version: String, iconsFile: File) {
        // Material Symbols ships the same set of icons across all of its styles (outlined, rounded, sharp), so we only
        // need a single list of names. We still fetch every family, though, to verify that assumption holds.
        val repo = MaterialDesignIconsRepo(commit = version)
        val namesByStyle = Style.entries.associateWith { style -> repo.fetchCodepointNames(style.codepointsPath) }

        iconsFile.writeText(iconsFileTextFor(version, namesByStyle))
        println("Wrote ${iconsFile.name}")
    }

    /** Converts the icon names listed in each Material Symbols style's font into the contents of our icons file. */
    internal fun iconsFileTextFor(version: String, namesByStyle: Map<Style, List<String>>): String {
        val (primaryStyle, names) = namesByStyle.entries.first()
        namesByStyle.forEach { (style, styleNames) ->
            if (styleNames.toSet() != names.toSet()) {
                val missing = names - styleNames.toSet()
                val extra = styleNames - names.toSet()
                error(
                    "Icon names for ${style.familyName} differ from ${primaryStyle.familyName}, " +
                        "but this task assumes they are the same. " +
                        "Missing: ${missing.take(10)}${if (missing.size > 10) " (+${missing.size - 10} more)" else ""}, " +
                        "extra: ${extra.take(10)}${if (extra.size > 10) " (+${extra.size - 10} more)" else ""}"
                )
            }
        }

        return buildString {
            appendLine(AutogeneratedNotice.IconsFile("${MsIconSet.gitHubRepo} @ $version").text)
            names.forEach { appendLine(it) }
        }
    }

    override fun generateBindings(iconsFile: File, packageName: String, outputDir: File) {
        val methodNamer = MsIconSet.methodNamer

        val iconRawNames = iconsFile
            .readLines()
            .map { it.trim() }
            .filter { line -> !line.startsWith("#") && line.isNotBlank() }
            .let(methodNamer::dropSeparatorCollisions)

        methodNamer.checkUnique(iconRawNames)

        val iconsHeader =
            """
            |${AutogeneratedNotice.Bindings(iconsFile).text}
            |//@formatter:off
            |@file:Suppress("unused", "SpellCheckingInspection")
            |
            |package $packageName
            |
            |import androidx.compose.runtime.*
            |import com.varabyte.kobweb.compose.ui.Modifier
            |import ${packageName}.MsIconStyle.*
            |
            """.trimMargin()

        val packageDir = outputDir.preparePackageDir(packageName)

        packageDir.resolve("_MsIcon.kt").writeText(
            iconsHeader + $$"""
            |import com.varabyte.kobweb.compose.ui.toAttrs
            |import org.jetbrains.compose.web.dom.Span
            |import org.jetbrains.compose.web.dom.Text
            |
            |enum class MsIconStyle {
            |    OUTLINED,
            |    ROUNDED,
            |    SHARP;
            |}
            |
            |@Deprecated("Use MsIconStyle instead", ReplaceWith("MsIconStyle"))
            |typealias IconStyle = MsIconStyle
            |
            |private fun MsIconStyle.toClassNameSuffix(): String {
            |    return when (this) {
            |        OUTLINED -> "-outlined"
            |        ROUNDED -> "-rounded"
            |        SHARP -> "-sharp"
            |    }
            |}
            |
            |@Composable
            |fun MsIcon(
            |    name: String,
            |    modifier: Modifier,
            |    style: MsIconStyle = OUTLINED,
            |) {
            |    Span(
            |        attrs = modifier.toAttrs { classes("material-symbols${style.toClassNameSuffix()}") }
            |    ) {
            |        Text(name)
            |    }
            |}
            |
            """.trimMargin()
        )

        for (rawName in iconRawNames) {
            val iconCode = "@Composable fun ${methodNamer.nameFor(rawName)}(modifier: Modifier = Modifier, style: MsIconStyle = OUTLINED) = MsIcon(\"$rawName\", modifier, style)"

            // Name files after the raw icon name, not the method name. Method names can differ only by case, which
            // collides on case-insensitive file systems and is rejected by the Kotlin/JS compiler.
            packageDir.resolve("$rawName.kt").writeText("$iconsHeader\n$iconCode")
        }
    }
}
