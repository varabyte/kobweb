package com.varabyte.kobweb.icons.codegen.fa

import com.varabyte.kobweb.icons.codegen.IconSetCodegen
import com.varabyte.kobweb.icons.codegen.fetch.GitHubRepo
import com.varabyte.kobweb.icons.codegen.generate.AutogeneratedNotice
import com.varabyte.kobweb.icons.codegen.generate.checkUnique
import com.varabyte.kobweb.icons.codegen.generate.IconMethodNamer
import com.varabyte.kobweb.icons.codegen.generate.preparePackageDir
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.io.File

/**
 * Font Awesome's free icons (https://fontawesome.com), rendered with its icon font.
 *
 * The icons file lists icon names per style, one style per line:
 * ```
 * fas=0,1,2,...,address-book,...
 * far=address-book,...
 * fab=42-group,500px,...
 * ```
 *
 * where `fas`, `far`, and `fab` are Font Awesome's short style prefixes for its solid, regular, and brands styles. Each
 * icon becomes a composable that renders it, e.g. `FaAddressBook`.
 */
class FaCodegen : IconSetCodegen {
    override val id = "fa"

    /**
     * Font Awesome's free icon styles, in the order they're listed in the icons file.
     *
     * @property shortPrefix Font Awesome's short style prefix (e.g. "fas"), which is also its CSS class and its key in
     *   the icons file.
     */
    internal enum class Style(val shortPrefix: String) {
        SOLID("fas"),
        REGULAR("far"),
        BRANDS("fab");

        /** Font Awesome's name for this style, as used in `metadata/icons.json` (e.g. "solid"). */
        val styleName get() = name.lowercase()
    }

    override fun stylesheetUrl(version: String) =
        "https://cdnjs.cloudflare.com/ajax/libs/font-awesome/$version/css/all.min.css"

    override fun fetch(version: String, iconsFile: File) {
        val iconsJson = gitHubRepo.fetchFileText(version, "metadata/icons.json")

        iconsFile.writeText(iconsFileTextFor(version, iconsJson))
        println("Wrote ${iconsFile.name}")
    }

    /** Converts the contents of Font Awesome's `metadata/icons.json` file into the contents of our icons file. */
    internal fun iconsFileTextFor(version: String, iconsJson: String): String {
        // Each entry lists the styles available for free, e.g. "address-book": {"free": ["solid", "regular"], ...}
        val freeStyles: Map<String, Set<String>> = Json.parseToJsonElement(iconsJson).jsonObject
            .mapValues { (_, icon) ->
                icon.jsonObject["free"]?.jsonArray?.map { it.jsonPrimitive.content }?.toSet().orEmpty()
            }
            // Generated functions can either pick between solid and regular styles or render a brand, not both. In
            // practice, only the "font-awesome" icon is a brand that also has other styles.
            .mapValues { (_, styles) ->
                if (styles.size > 1) styles - Style.BRANDS.styleName else styles
            }

        return buildString {
            appendLine(AutogeneratedNotice.IconsFile("FortAwesome/Font-Awesome @ $version").text)
            for (style in Style.entries) {
                val names = freeStyles.filterValues { style.styleName in it }.keys
                appendLine("${style.shortPrefix}=${names.joinToString(",")}")
            }
        }
    }

    override fun generateBindings(iconsFile: File, packageName: String, outputDir: File) {
        // {SOLID=[ad, address-book, address-card, ...], REGULAR=[address-book, address-card, angry, ...], ... }
        val iconRawNames = iconsFile
            .readLines()
            .filter { line -> !line.startsWith("#") }
            .associate { line ->
                val (shortPrefix, names) = line.split("=", limit = 2)
                val style = Style.entries.find { it.shortPrefix == shortPrefix }
                    ?: error("Unexpected style prefix: $shortPrefix")

                style to names
                    .split(",")
                    .filter { it.isNotEmpty() }
                    // Some icons have aliases that differ only by dashes (e.g. "print-shop" and "printshop"), which
                    // would generate near-identical method names (e.g. FaPrintShop and FaPrintshop). Keep only the
                    // longest version of each name, since its dashes give us more readable method names.
                    .groupBy { it.replace("-", "") }
                    .map { (_, values) -> values.maxBy { it.length } }
            }

        // For each icon name, figure out what styles it's available in. This will affect the function signature we
        // generate, e.g. {ad=[SOLID], address-book=[SOLID, REGULAR], address-card=[SOLID, REGULAR], ...}
        val iconStyles = mutableMapOf<String, MutableSet<Style>>()
        iconRawNames.forEach { (style, rawNames) ->
            rawNames.forEach { rawName -> iconStyles.getOrPut(rawName) { mutableSetOf() }.add(style) }
        }

        val invalidGroupings = iconStyles.filterNot { (_, styles) ->
            styles.size == 1 || styles == setOf(Style.SOLID, Style.REGULAR)
        }
        check(invalidGroupings.isEmpty()) {
            "Found unexpected groupings. An icon should only have one style OR it can have solid and regular versions: $invalidGroupings"
        }

        methodNamer.checkUnique(iconStyles.keys)

        val iconsHeader =
            """
            |${AutogeneratedNotice.Bindings(iconsFile).text}
            |//@formatter:off
            |@file:Suppress("unused", "SpellCheckingInspection")
            |
            |package $packageName
            |
            |import androidx.compose.runtime.*
            |import com.varabyte.kobweb.compose.ui.Modifier
            |
            """.trimMargin()

        val packageDir = outputDir.preparePackageDir(packageName)

        packageDir.resolve("_FaIcon.kt").writeText(
            iconsHeader + $$"""
            |import com.varabyte.kobweb.compose.ui.toAttrs
            |import org.jetbrains.compose.web.dom.Span
            |
            |// Brand icons have their own style ("fab"), but never offer a choice, so they use FaBrandIcon instead.
            |// See: https://docs.fontawesome.com/web/add-icons/how-to
            |enum class FaIconStyle(internal val className: String) {
            |    SOLID("fas"),
            |    REGULAR("far");
            |}
            |
            |// See: https://fontawesome.com/docs/web/style/size
            |enum class FaIconSize(internal val className: String) {
            |    // Relative sizes
            |    XXS("fa-2xs"),
            |    XS("fa-xs"),
            |    SM("fa-sm"),
            |    LG("fa-lg"),
            |    XL("fa-xl"),
            |    XXL("fa-2xl"),
            |
            |    // Literal sizes
            |    X1("fa-1x"),
            |    X2("fa-2x"),
            |    X3("fa-3x"),
            |    X4("fa-4x"),
            |    X5("fa-5x"),
            |    X6("fa-6x"),
            |    X7("fa-7x"),
            |    X8("fa-8x"),
            |    X9("fa-9x"),
            |    X10("fa-10x");
            |}
            |
            |@Composable
            |fun FaIcon(
            |    name: String,
            |    modifier: Modifier,
            |    style: FaIconStyle = FaIconStyle.REGULAR,
            |    size: FaIconSize? = null,
            |) {
            |    FaIconSpan(style.className, name, modifier, size)
            |}
            |
            |@Composable
            |fun FaBrandIcon(
            |    name: String,
            |    modifier: Modifier,
            |    size: FaIconSize? = null,
            |) {
            |    FaIconSpan("fab", name, modifier, size)
            |}
            |
            |@Composable
            |private fun FaIconSpan(styleClassName: String, name: String, modifier: Modifier, size: FaIconSize?) {
            |    Span(
            |        attrs = modifier.toAttrs {
            |            classes(styleClassName, "fa-$name")
            |            if (size != null) {
            |                classes(size.className)
            |            }
            |        }
            |    )
            |}
            |
            |// Kotlin can't alias enum entries, so this object keeps legacy calls like `FaStar(style = IconStyle.FILLED)`
            |// compiling
            |@Deprecated("Use FaIconStyle instead", ReplaceWith("FaIconStyle"))
            |object IconStyle {
            |    @Deprecated("Use FaIconStyle.SOLID instead", ReplaceWith("FaIconStyle.SOLID"))
            |    val FILLED = FaIconStyle.SOLID
            |
            |    @Deprecated("Use FaIconStyle.REGULAR instead", ReplaceWith("FaIconStyle.REGULAR"))
            |    val OUTLINE = FaIconStyle.REGULAR
            |}
            |
            |@Deprecated("Use FaIconSize instead", ReplaceWith("FaIconSize"))
            |typealias IconSize = FaIconSize
            |
            """.trimMargin()
        )

        for ((rawName, styles) in iconStyles) {
            val methodName = methodNamer.methodNameFor(rawName)
            val iconCode = if (styles.size == 2) {
                "@Composable fun $methodName(modifier: Modifier = Modifier, style: FaIconStyle = FaIconStyle.REGULAR, size: FaIconSize? = null) = FaIcon(\"$rawName\", modifier, style, size)"
            } else {
                val renderCall = when (val style = styles.single()) {
                    Style.BRANDS -> "FaBrandIcon(\"$rawName\", modifier, size)"
                    else -> "FaIcon(\"$rawName\", modifier, FaIconStyle.${style.name}, size)"
                }
                "@Composable fun $methodName(modifier: Modifier = Modifier, size: FaIconSize? = null) = $renderCall"
            }

            // Name files after the raw icon name, not the method name. Method names can differ only by case, which
            // collides on case-insensitive file systems and is rejected by the Kotlin/JS compiler.
            packageDir.resolve("$rawName.kt").writeText("$iconsHeader\n$iconCode")
        }
    }

    private val gitHubRepo = GitHubRepo("FortAwesome/Font-Awesome")

    private val methodNamer = IconMethodNamer(prefix = "Fa", separator = '-')
}
