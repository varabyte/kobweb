package com.varabyte.kobweb.icons.codegen.material

import com.varabyte.kobweb.icons.codegen.IconSet
import com.varabyte.kobweb.icons.codegen.generate.AutogeneratedNotice
import com.varabyte.kobweb.icons.codegen.generate.checkUnique
import com.varabyte.kobweb.icons.codegen.generate.IconMethodNamer
import com.varabyte.kobweb.icons.codegen.generate.preparePackageDir
import java.io.File

/**
 * Google's Material Icons (https://developers.google.com/fonts/docs/material_icons), rendered with its icon fonts.
 *
 * Its version is a commit in https://github.com/google/material-design-icons, which has no release tags.
 *
 * The icons file lists icon names per style, one style per line:
 * ```
 * mdi=10k,10mp,...
 * mdio=10k,10mp,...
 * mdir=...
 * mdis=...
 * mdit=...
 * ```
 *
 * for the filled, outlined, rounded, sharp, and two-toned styles. Each icon becomes a composable that renders it, e.g.
 * `MdiArrowBack`.
 */
class MdiIconSet : IconSet {
    override val id = "mdi"

    /**
     * Material Icons' styles, each with its own font, in the order they're listed in the icons file.
     *
     * @property key The style's key in the icons file.
     * @property fontName The base name of the style's font files in google/material-design-icons.
     */
    internal enum class Style(val key: String, val fontName: String) {
        FILLED("mdi", "MaterialIcons-Regular"),
        OUTLINED("mdio", "MaterialIconsOutlined-Regular"),
        ROUNDED("mdir", "MaterialIconsRound-Regular"),
        SHARP("mdis", "MaterialIconsSharp-Regular"),
        TWO_TONED("mdit", "MaterialIconsTwoTone-Regular");

        /** The path of the font's codepoints file in google/material-design-icons, which lists its icon names. */
        val codepointsPath get() = "font/$fontName.codepoints"
    }

    // Google Fonts doesn't version its stylesheets
    override fun stylesheetUrl(version: String) =
        "https://fonts.googleapis.com/css2?family=Material+Icons&family=Material+Icons+Outlined&family=Material+Icons+Two+Tone&family=Material+Icons+Round&family=Material+Icons+Sharp"

    override fun fetch(version: String, iconsFile: File) {
        val repo = MaterialDesignIconsRepo(commit = version)
        val lines = Style.entries.map { style ->
            val names = repo.fetchCodepointNames(style.codepointsPath)
            "${style.key}=${names.joinToString(",")}"
        }

        iconsFile.writeText(
            (listOf(AutogeneratedNotice.IconsFile("google/material-design-icons @ $version").text) + lines)
                .joinToString("\n")
        )
        println("Wrote ${iconsFile.name}")
    }

    override fun generateBindings(iconsFile: File, packageName: String, outputDir: File) {
        val iconRawNames: Map<Style, List<String>> = iconsFile
            .readLines()
            .filter { line -> !line.startsWith("#") }
            .associate { line ->
                val (key, names) = line.split("=", limit = 2)
                val style = Style.entries.find { it.key == key } ?: error("Unexpected style grouping: $key")

                style to names
                    .split(",")
                    .filter { it.isNotEmpty() }
                    // Some icons have aliases that differ only by underscores (e.g. "print_shop" and "printshop"),
                    // which would generate near-identical method names (e.g. MdiPrintShop and MdiPrintshop). Keep only
                    // the longest version of each name, since its underscores give us more readable method names.
                    .groupBy { it.replace("_", "") }
                    .map { (_, values) -> values.maxBy { it.length } }
            }

        // For each icon name, figure out what styles it's available in. This affects the function signature we generate.
        val iconStyleGroups = mutableMapOf<String, MutableSet<Style>>()
        iconRawNames.forEach { (style, rawNames) ->
            rawNames.forEach { rawName -> iconStyleGroups.getOrPut(rawName) { mutableSetOf() }.add(style) }
        }

        methodNamer.checkUnique(iconStyleGroups.keys)

        val iconsHeader =
            """
            |${AutogeneratedNotice.Bindings(iconsFile).text}
            |//@formatter:off
            |@file:Suppress("unused", "SpellCheckingInspection")
            |
            |package $packageName
            |
            |import androidx.compose.runtime.*
            |import com.varabyte.kobweb.compose.ui.Modifier
            |import ${packageName}.MdiIconStyle.*
            |
            """.trimMargin()

        val packageDir = outputDir.preparePackageDir(packageName)

        packageDir.resolve("_MdiIcon.kt").writeText(
            iconsHeader + $$"""
            |import com.varabyte.kobweb.compose.ui.toAttrs
            |import org.jetbrains.compose.web.dom.Span
            |import org.jetbrains.compose.web.dom.Text
            |
            |enum class MdiIconStyle {
            |    FILLED,
            |    OUTLINED,
            |    ROUNDED,
            |    SHARP,
            |    TWO_TONED;
            |}
            |
            |@Deprecated("Use MdiIconStyle instead", ReplaceWith("MdiIconStyle"))
            |typealias IconStyle = MdiIconStyle
            |
            |private fun MdiIconStyle.toClassNameSuffix(): String {
            |    return when (this) {
            |        FILLED -> ""
            |        OUTLINED -> "-outlined"
            |        ROUNDED -> "-round"
            |        SHARP -> "-sharp"
            |        TWO_TONED -> "-two-tone"
            |    }
            |}
            |
            |internal fun MdiIconStyle.assertValidStyle(methodName: String, vararg validStyles: MdiIconStyle) {
            |    if (this !in validStyles) {
            |        error("Attempted to render \"$methodName\" with style $this. Must be one of: ${validStyles.joinToString()}")
            |    }
            |}
            |
            |@Composable
            |fun MdiIcon(
            |    name: String,
            |    modifier: Modifier,
            |    style: MdiIconStyle = FILLED,
            |) {
            |    Span(
            |        attrs = modifier.toAttrs { classes("material-icons${style.toClassNameSuffix()}") }
            |    ) {
            |        Text(name)
            |    }
            |}
            |
            |@Deprecated("Use MdiIcon instead", ReplaceWith("MdiIcon(name, modifier, style)"))
            |@Composable
            |fun MdIcon(name: String, modifier: Modifier, style: MdiIconStyle = FILLED) = MdiIcon(name, modifier, style)
            |
            """.trimMargin()
        )

        for ((rawName, styles) in iconStyleGroups) {
            // TODO(194): Figure out how ligature fallbacks to work, if people report us breaking on legacy browsers.
            //  See also: https://developers.google.com/fonts/docs/material_icons#using_the_icons_in_html
            val methodName = methodNamer.methodNameFor(rawName)
            val iconCode = when (styles.size) {
                // A rare solo-style icon? No need to allow a user to pass in a style parameter in that case
                1 -> "@Composable fun $methodName(modifier: Modifier = Modifier) = MdiIcon(\"$rawName\", modifier, ${styles.first().name})"

                // This icon supports all styles. No need to assert input parameters.
                Style.entries.size -> "@Composable fun $methodName(modifier: Modifier = Modifier, style: MdiIconStyle = FILLED) = MdiIcon(\"$rawName\", modifier, style)"

                // Not all styles are valid. For now, we throw a runtime exception (via assertValidStyle) to inform
                // the user about this, but we can always decide to relax this later.
                else -> "@Composable fun $methodName(modifier: Modifier = Modifier, style: MdiIconStyle = ${styles.first().name}) = MdiIcon(\"$rawName\", modifier, style.also { it.assertValidStyle(\"$methodName\", ${styles.joinToString { it.name }}) })"
            }

            // Name files after the raw icon name, not the method name. Method names can differ only by case, which
            // collides on case-insensitive file systems and is rejected by the Kotlin/JS compiler.
            packageDir.resolve("$rawName.kt").writeText("$iconsHeader\n$iconCode")
        }
    }

    private val methodNamer = IconMethodNamer(prefix = "Mdi", separator = '_')
}
